import {
  pgTable,
  serial,
  text,
  integer,
  bigint,
  date,
  timestamp,
} from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";
import { accountsTable } from "./accounts";
import { jobsTable } from "./jobs";
import { customersTable } from "./customers";
import { vendorsTable } from "./vendors";
import { payrollRunsTable } from "./payroll";
import { billsTable } from "./bills";

export const transactionsTable = pgTable("transactions", {
  id: serial("id").primaryKey(),
  date: date("date", { mode: "string" }).notNull(),
  type: text("type").notNull(),
  num: text("num"),
  partyName: text("party_name"),
  description: text("description"),
  accountId: integer("account_id")
    .notNull()
    .references(() => accountsTable.id, { onDelete: "restrict" }),
  splitAccountId: integer("split_account_id").references(
    () => accountsTable.id,
    { onDelete: "set null" },
  ),
  // DEPRECATED legacy column: free-text split account name from the old
  // QuickBooks import. Kept in the schema only so the publish-time diff does
  // NOT drop it before production rows are backfilled onto split_account_id
  // (see artifacts/api-server/src/lib/splitAccountBackfill.ts). The API never
  // reads or writes it. Drop it in the "retire the free-text split account
  // field" follow-up once production has no rows using it.
  splitAccount: text("split_account"),
  jobId: integer("job_id").references(() => jobsTable.id, {
    onDelete: "set null",
  }),
  customerId: integer("customer_id").references(() => customersTable.id, {
    onDelete: "set null",
  }),
  vendorId: integer("vendor_id").references(() => vendorsTable.id, {
    onDelete: "set null",
  }),
  payrollRunId: integer("payroll_run_id").references(() => payrollRunsTable.id, {
    onDelete: "cascade",
  }),
  // Source bill when this ledger row was generated by posting a bill.
  // Cascade: deleting a bill removes the ledger rows it generated, exactly
  // like payroll runs, so the books never keep orphaned bill postings.
  billId: integer("bill_id").references(() => billsTable.id, {
    onDelete: "cascade",
  }),
  amountCents: bigint("amount_cents", { mode: "number" }).notNull(),
  createdAt: timestamp("created_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
});

export const insertTransactionSchema = createInsertSchema(
  transactionsTable,
).omit({
  id: true,
  createdAt: true,
  updatedAt: true,
  // Legacy free-text column — never accepted as input.
  splitAccount: true,
  // Server-managed link to the source bill — never accepted as input.
  billId: true,
});
export type InsertTransaction = z.infer<typeof insertTransactionSchema>;
export type Transaction = typeof transactionsTable.$inferSelect;
