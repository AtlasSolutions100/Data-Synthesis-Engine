import { describe, it, expect, beforeAll, afterAll, vi } from "vitest";
import express, {
  type Express,
  type Request,
  type Response,
  type NextFunction,
  type IRouter,
} from "express";
import request from "supertest";
import { eq } from "drizzle-orm";
import {
  db,
  accountsTable,
  vendorsTable,
  billsTable,
  transactionsTable,
} from "@workspace/db";

/**
 * Deleting a bill must never silently erase historical imported ledger rows.
 * Backfilled legacy bills (posted_to_ledger = false) can be linked to
 * QuickBooks-imported transactions; the delete route unlinks those rows
 * (bill_id → NULL) instead of letting the FK cascade delete them. Rows the
 * API generated by posting a bill (posted_to_ledger = true) still cascade.
 */

function buildApp(...routers: IRouter[]): Express {
  const app = express();
  app.use(express.json());
  app.use((req: Request, _res: Response, next: NextFunction) => {
    req.log = { error: vi.fn(), warn: vi.fn(), info: vi.fn() } as never;
    next();
  });
  for (const r of routers) app.use("/api", r);
  return app;
}

let app: Express;
let vendorId: number;
let acctId: number;
const txIds: number[] = [];
const billIds: number[] = [];

beforeAll(async () => {
  const { default: billsRouter } = await import("./bills");
  app = buildApp(billsRouter);

  const [vendor] = await db
    .insert(vendorsTable)
    .values({ name: "TEST-DU Vendor" })
    .returning();
  vendorId = vendor.id;
  const [acct] = await db
    .insert(accountsTable)
    .values({ number: "TEST-DU-5000", name: "Test DU Expense", type: "expense" })
    .returning();
  acctId = acct.id;
});

afterAll(async () => {
  for (const id of txIds) {
    await db.delete(transactionsTable).where(eq(transactionsTable.id, id));
  }
  for (const id of billIds) {
    await db.delete(billsTable).where(eq(billsTable.id, id));
  }
  await db.delete(accountsTable).where(eq(accountsTable.id, acctId));
  await db.delete(vendorsTable).where(eq(vendorsTable.id, vendorId));
});

describe("DELETE /bills/:id and linked ledger rows", () => {
  it("unlinks imported ledger rows on a non-posted (backfilled) bill instead of deleting them", async () => {
    // Legacy imported bill: created directly with postedToLedger = false,
    // then linked to a historical imported ledger row (the backfill).
    const [bill] = await db
      .insert(billsTable)
      .values({
        vendorId,
        billNumber: "TEST-DU-LEGACY-1",
        date: "2097-01-15",
        postedToLedger: false,
      })
      .returning();
    billIds.push(bill.id);
    const [imported] = await db
      .insert(transactionsTable)
      .values({
        date: "2097-01-15",
        type: "bill",
        num: "TEST-DU-LEGACY-1",
        accountId: acctId,
        vendorId,
        amountCents: 12345,
        billId: bill.id,
      })
      .returning();
    txIds.push(imported.id);

    const res = await request(app).delete(`/api/bills/${bill.id}`);
    expect(res.status).toBe(204);
    billIds.splice(billIds.indexOf(bill.id), 1);

    // The historical imported row survives, just unlinked.
    const [row] = await db
      .select()
      .from(transactionsTable)
      .where(eq(transactionsTable.id, imported.id));
    expect(row).toBeDefined();
    expect(row.billId).toBeNull();
    expect(Number(row.amountCents)).toBe(12345);
  });

  it("still cascades generated ledger rows for API-posted bills", async () => {
    const created = await request(app).post("/api/bills").send({
      vendorId,
      billNumber: "TEST-DU-POSTED-1",
      date: "2097-02-01",
      lines: [{ accountId: acctId, description: "posted", amountCents: 5000 }],
    });
    expect(created.status).toBe(201);
    const billId = created.body.id;
    billIds.push(billId);
    expect(
      await db
        .select()
        .from(transactionsTable)
        .where(eq(transactionsTable.billId, billId)),
    ).toHaveLength(1);

    const res = await request(app).delete(`/api/bills/${billId}`);
    expect(res.status).toBe(204);
    billIds.splice(billIds.indexOf(billId), 1);
    expect(
      await db
        .select()
        .from(transactionsTable)
        .where(eq(transactionsTable.billId, billId)),
    ).toHaveLength(0);
  });
});
